"""Сборка файла разметки для напарника: .xlsx с подсказками и .csv с BOM.

Зачем .xlsx, а не только .csv: Excel на macOS открывает CSV в MacRoman, если в
файле нет BOM, и кириллица превращается в мусор — это и произошло у напарника.
BOM добавлен, но .xlsx надёжнее в принципе: кодировка там не при чём, а заодно
можно дать выпадающие списки, чтобы коды типов нельзя было написать с опечаткой.

    PYTHONPATH=tools .venv/bin/python tools/make_labeling_xlsx.py [каталог]
"""
import sys
from pathlib import Path

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

sys.path.insert(0, str(Path(__file__).resolve().parent))
from evaluate import LABELS  # noqa: E402

DUP = {"Х-47", "Х-48"}

# ВАЖНО: это коды НАБЛЮДАЕМЫХ действий, а не список нарушений. Часть из них сама
# по себе нарушением не является (пересчёт руками, открытый сейф, сумка на столе).
# Нормативная оценка выносится отдельной колонкой «статус», и это принципиально:
# смешение наблюдения с приговором — главное замечание по первой версии файла.
TYPES = [
    ("manual_count", "пересчёт наличных руками, счётная машина не используется"),
    ("cash_unattended", "наличные лежат на столе, кассир их не контролирует"),
    ("cash_handover", "деньги переданы из рук в руки / положены мимо лотка"),
    ("left_workplace", "кассир ушёл с рабочего места, не убрав ценности"),
    ("cabin_open", "дверь кассовой кабины открыта / кабина не заперта"),
    ("safe_open", "сейф или шкаф оставлен открытым"),
    ("outsider", "посторонний в помещении во время операции с наличными"),
    ("food_drink", "стакан, кружка, банка, бутылка, еда на рабочем месте"),
    ("personal_bag", "личная сумка, рюкзак, пакет на рабочем месте"),
    ("sealed_bag", "инкассаторская сумка вне сейфа / передана без оформления"),
    ("phone_use", "кассир пользуется телефоном на рабочем месте"),
    ("other", "другое — обязательно описать словами в колонке «что происходит»"),
    ("unclear", "не видно, что именно нарушено"),
]

# Ролик -> что сейчас выдаёт сервис. Первыми идут те, где он не находит ничего:
# про них у нас нет никакой информации, и там каждая строка ценнее всего.
FOUND = {
    "Х-4": "находит «посторонние в помещении» на 42 с",
    "Х-11": "находит «рабочее место без работника»",
    "Х-13": "находит «рабочее место без работника» на 57 с",
    "Х-15": "находит «инкассаторская сумка вне сейфа»",
    "Х-24": "находит «напиток или еда»",
    "Х-26": "находит «рабочее место без работника» на 17 с",
    "Х-30": "находит «рабочее место без работника» на 0 с",
    "Х-32": "находит «рабочее место без работника»",
    "Х-38": "находит «посторонние в помещении»",
    "Х-40": "находит «личная сумка на рабочем месте»",
    "Х-46": "находит «напиток или еда»",
}
HEAD = PatternFill("solid", fgColor="1F3864")
ALT = PatternFill("solid", fgColor="EDF2FA")


def rows() -> list[tuple[str, int, str]]:
    out = []
    for name, secs in LABELS.items():
        if not secs or name in DUP:
            continue
        for s in secs:
            out.append((name, s, FOUND.get(name, "программа не находит ничего")))
    # сначала ненайденные, внутри групп — по номеру ролика
    out.sort(key=lambda r: (r[2] != "программа не находит ничего",
                            len(r[0]), r[0], r[1]))
    return out


def build(dst_dir: Path) -> None:
    wb = Workbook()

    ws = wb.active
    ws.title = "разметка"
    cols = [("ролик", 12), ("секунда организаторов", 12),
            ("что НАБЛЮДАЕТСЯ (код)", 24),
            ("что происходит, 5-15 слов", 44),
            ("чем это видно на экране — предмет, место, действие", 56),
            ("уверенность", 13),
            ("статус", 20),
            ("t_начало", 10), ("t_доказательство", 14), ("t_конец", 10),
            ("что мешает решить (если unclear)", 34),
            ("что выдаёт программа сейчас", 38)]
    ws.append([c[0] for c in cols])
    for i, (_, w) in enumerate(cols, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
        c = ws.cell(row=1, column=i)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = HEAD
        c.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[1].height = 34

    data = rows()
    for n, (name, sec, note) in enumerate(data, start=2):
        ws.append([name, sec, "", "", "", "", "", None, None, None, "", note])
        for i in range(1, len(cols) + 1):
            cell = ws.cell(row=n, column=i)
            cell.alignment = Alignment(wrap_text=True, vertical="top")
            if n % 2 == 0:
                cell.fill = ALT
        ws.cell(row=n, column=12).font = Font(italic=True, color="808080")
        ws.row_dimensions[n].height = 30

    last = len(data) + 1
    dv = DataValidation(type="list", formula1='"' + ",".join(t for t, _ in TYPES) + '"',
                        allow_blank=True, showDropDown=False)
    dv.error = "Выберите код из списка на листе «коды типов»"
    dv.errorTitle = "Неизвестный код"
    ws.add_data_validation(dv)
    dv.add(f"C2:C{last}")

    dvc = DataValidation(type="list", formula1='"high,med,low"', allow_blank=True,
                         showDropDown=False)
    ws.add_data_validation(dvc)
    dvc.add(f"F2:F{last}")

    # Статус — отдельно от наблюдения: наблюдаемое действие и вывод о нарушении
    # это разные вещи, и смешивать их нельзя (см. лист «как заполнять»).
    dvs = DataValidation(
        type="list",
        formula1='"похоже_на_нарушение,это_норма,не_могу_решить"',
        allow_blank=True, showDropDown=False)
    ws.add_data_validation(dvs)
    dvs.add(f"G2:G{last}")

    ws.freeze_panes = "C2"

    # лист с кодами — чтобы не держать инструкцию открытой рядом
    ws2 = wb.create_sheet("коды типов")
    ws2.append(["код", "что значит"])
    for i, w in ((1, 22), (2, 70)):
        ws2.column_dimensions[get_column_letter(i)].width = w
        c = ws2.cell(row=1, column=i)
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = HEAD
    for code, desc in TYPES:
        ws2.append([code, desc])
    for r in range(2, len(TYPES) + 2):
        ws2.cell(row=r, column=2).alignment = Alignment(wrap_text=True)

    ws3 = wb.create_sheet("как заполнять")
    text = [
        "Главное: эти ролики УЖЕ помечены организаторами как нарушения",
        "",
        "Твоя задача — не решить, нарушение это или нет. Организаторы уже решили:",
        "в их таблице по каждому из этих роликов стоит отметка и секунда. Задача —",
        "понять, ЧТО ИМЕННО они там увидели. Это вопрос про картинку, а не про право.",
        "",
        "Поэтому наблюдение и нормативная оценка разнесены по разным колонкам.",
        "«Код» — что видно глазами. «Статус» — считаешь ли ты это нарушением.",
        "Эти вещи путать нельзя: пересчёт денег руками, открытый сейф или",
        "инкассаторская сумка на столе сами по себе нарушением НЕ являются —",
        "оборудование могло применяться до или после, сейф открыт для операции,",
        "сумка может быть в процессе приёма. Код ставь по тому, что видно;",
        "статус — отдельно и осторожно.",
        "",
        "Как заполнять",
        "",
        "1. Посмотреть ролик ЦЕЛИКОМ, а не только окрестность секунды. Контекст",
        "   решает: закончено ли обслуживание клиента, чьи это деньги, чья сумка.",
        "2. Вернуться к секунде организаторов и понять, что они отметили.",
        "3. Заполнить код, описание, «чем это видно», уверенность.",
        "4. Поставить статус: похоже_на_нарушение / это_норма / не_могу_решить.",
        "   «не_могу_решить» — нормальный ответ, и очень полезный. В колонке",
        "   «что мешает решить» написать, чего именно не видно: обзор обрезан,",
        "   не видно клиента, неясно чья сумка, не видно начала эпизода.",
        "5. Времена: t_начало — начало наблюдаемого действия, t_доказательство —",
        "   самый убедительный кадр, t_конец — конец эпизода. Секунду организаторов",
        "   НЕ менять, она в своей колонке.",
        "",
        "Три правила, которые важнее скорости",
        "",
        "1. Не угадывать. «не_могу_решить» честнее выдуманного типа: по выдуманному",
        "   будет построено правило, которое даст ложные срабатывания у жюри.",
        "",
        "2. Колонка «чем это видно» — главная. Писать физически наблюдаемое:",
        "   не «нарушение кассовой дисциплины», а «зелёная сумка лежит на",
        "   столешнице, кассир стоит у стеклянной стены в двух метрах от стола».",
        "   И не писать выводов, которых не видно: «переложил различимые банкноты",
        "   со стола в карман» — можно; «украл деньги» — нельзя.",
        "",
        "3. Если в ролике несколько эпизодов — несколько строк. Одно длящееся",
        "   состояние заново каждую секунду размечать не надо. Про Х-4 известно,",
        "   что он размечен дважды, на 57 и 68 секунде — обе строки есть.",
        "",
        "Если начало эпизода не попало в запись, не выдавай начало файла за начало",
        "нарушения: оставь t_начало пустым и напиши в «что мешает решить».",
        "",
        "Колонка «что выдаёт программа сейчас» — подсказка, а не ответ. Расхождение",
        "программы с человеком — это и есть то, что мы ищем.",
        "",
        "Первые 10 строк — ролики, где программа не находит ничего. Про них у нас",
        "нет никакой информации, и каждая строка здесь даёт больше всех остальных.",
        "",
        "Один ролик — 3-5 минут, если смотреть целиком. Всего полтора-два часа.",
        "",
        "Пример заполненной строки",
        "",
        "  ролик: Х-46 | секунда организаторов: 11",
        "  код:              food_drink",
        "  что происходит:   кассир работает, рядом на столе стоит стакан с напитком",
        "  чем это видно:    прозрачный стакан слева от клавиатуры, в 20 см от рук,",
        "                    стоит весь ролик, никто его не убирает",
        "  уверенность:      high",
        "  статус:           похоже_на_нарушение",
        "  времена:          t_начало 9.0, t_доказательство 11.0, t_конец 19.0",
        "",
        "Ещё пример — когда решить нельзя",
        "",
        "  ролик: Х-20 | секунда организаторов: 5",
        "  код:              manual_count",
        "  что происходит:   кассир перебирает в руках пачку купюр",
        "  чем это видно:    купюры в руках, счётная машина справа, к ней не тянется",
        "  уверенность:      med",
        "  статус:           не_могу_решить",
        "  что мешает:       не видно, применялась ли машина до или после; начало",
        "                    эпизода за пределами записи",
    ]
    ws3.column_dimensions["A"].width = 100
    for i, line in enumerate(text, start=1):
        ws3.cell(row=i, column=1, value=line)
        if i == 1 or line in ("Как заполнять",
                              "Три правила, которые важнее скорости",
                              "Пример заполненной строки",
                              "Ещё пример — когда решить нельзя"):
            ws3.cell(row=i, column=1).font = Font(bold=True, size=13)

    dst_dir.mkdir(parents=True, exist_ok=True)
    xlsx = dst_dir / "РАЗМЕТКА.xlsx"
    wb.save(xlsx)

    # CSV с BOM — на случай, если удобнее текстом; Excel на macOS без BOM
    # открывает файл в MacRoman и кириллица превращается в мусор
    csv = dst_dir / "РАЗМЕТКА-запасной-вариант.csv"
    lines = ["video;sec;type;what;cue;conf"]
    lines += [f"{n};{s};;;;" for n, s, _ in data]
    csv.write_text("\n".join(lines) + "\n", encoding="utf-8-sig")

    print(f"{xlsx}  — {len(data)} строк, выпадающие списки, 3 листа")
    print(f"{csv}  — то же в CSV, UTF-8 с BOM")


if __name__ == "__main__":
    build(Path(sys.argv[1] if len(sys.argv) > 1 else "annotation/out"))
